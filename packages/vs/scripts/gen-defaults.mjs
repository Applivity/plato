/**
 * Generate host/defaults.ts from the extension's contributes.configuration.
 *
 * The values are not copied by hand: the VS Code manifest is the one source,
 * so a default changed there reaches the Visual Studio host at build time.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const manifest = fileURLToPath(
  new URL('../../vscode/package.json', import.meta.url),
);
const target = fileURLToPath(new URL('../host/defaults.ts', import.meta.url));

const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
const properties = pkg?.contributes?.configuration?.properties ?? {};

const defaults = {};
for (const [key, value] of Object.entries(properties)) {
  if (value !== null && typeof value === 'object' && 'default' in value) {
    defaults[key] = value.default;
  }
}

const body = `/**
 * Generated by scripts/gen-defaults.mjs from packages/vscode/package.json.
 * Do not edit by hand.
 */
export const DEFAULTS: Record<string, unknown> = ${JSON.stringify(
  defaults,
  null,
  2,
)};
`;

writeFileSync(target, body);
console.log(`defaults: ${Object.keys(defaults).length} keys -> ${target}`);
