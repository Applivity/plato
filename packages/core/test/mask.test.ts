/**
 * D49bb: masking replaces the refusal to read a protected file.
 *
 * The two tests that matter most are the fail-closed ones. Everything else is
 * behaviour; those are the safety property — a masker that returns the original
 * text for something it did not understand reports success while handing over the
 * secret, which is strictly worse than the refusal it replaced.
 */
import { beforeEach, describe, expect, it } from 'vitest';
import {
  MIN_SCRUB_LENGTH,
  createVault,
  hasPlaceholder,
  maskText,
  placeholder,
  placeholdersIn,
} from '../src/security/mask.js';
import { maskedFileNotice, unmaskableRefusal, unknownPlaceholderRefusal } from '../src/runtime/secretCopy.js';
import { configureSecrets, isSecretPath } from '../src/security/secrets.js';

const ENV = [
  '# local only',
  'API_KEY=sk-live-abc123456789',
  'DB_URL=postgres://user:pw@localhost/db',
  '',
  'export DEBUG=true',
].join('\n');

describe('maskText', () => {
  it('replaces every value with a placeholder that names its key', () => {
    const r = maskText(ENV);
    expect(r).not.toBeNull();
    expect(r!.masked).toContain('API_KEY=«masked:API_KEY»');
    expect(r!.masked).toContain('DB_URL=«masked:DB_URL»');
    expect(r!.masked).toContain('export DEBUG=«masked:DEBUG»');
  });

  it('leaks no value', () => {
    const r = maskText(ENV)!;
    expect(r.masked).not.toContain('sk-live-abc123456789');
    expect(r.masked).not.toContain('postgres://user:pw@localhost/db');
  });

  it('keeps the keys, the comments and the line structure', () => {
    const r = maskText(ENV)!;
    const before = ENV.split('\n');
    const after = r.masked.split('\n');
    expect(after.length).toBe(before.length);
    expect(after[0]).toBe('# local only');
    expect(after[3]).toBe('');
    for (let i = 0; i < before.length; i++) {
      const key = before[i]!.split('=')[0]!;
      expect(after[i]!.startsWith(key)).toBe(true);
    }
  });

  it('reports one pair per masked value, holding the real value', () => {
    const r = maskText(ENV)!;
    expect(r.pairs.length).toBe(3);
    expect(r.pairs.some(([ph, real]) => ph === placeholder('API_KEY') && real === 'sk-live-abc123456789')).toBe(true);
  });

  it('is idempotent — masking a masked file changes nothing', () => {
    const once = maskText(ENV)!.masked;
    const twice = maskText(once)!;
    expect(twice.masked).toBe(once);
  });

  // --- FAIL CLOSED ---------------------------------------------------------

  it('REFUSES a file it cannot account for, rather than passing the line through', () => {
    // The trap: a multi-line value. Masking the first line and passing the rest
    // through verbatim would hand over the body of the key.
    const pem = ['PRIVATE_KEY="-----BEGIN RSA PRIVATE KEY-----', 'MIIEowIBAAKCAQEA', '-----END RSA PRIVATE KEY-----"'].join('\n');
    expect(maskText(pem)).toBeNull();
  });

  it('REFUSES a file with no assignment at all', () => {
    expect(maskText('just some prose\nwith no values')).toBeNull();
  });

  it('REFUSES an empty file and a comments-only file', () => {
    expect(maskText('')).toBeNull();
    expect(maskText('# nothing here\n')).toBeNull();
  });

  it('REFUSES a sectioned ini whose values it cannot place', () => {
    expect(maskText('[section]\nkey=value')).toBeNull();
  });

  it('accepts blank lines, comments and a trailing newline', () => {
    expect(maskText('\n# c\nA=1\n// x\n; y\n')).not.toBeNull();
  });

  it('masks a value that was COMMENTED OUT rather than deleted', () => {
    // What people actually do while testing. A masker that passes comment lines
    // through hands this key over while the file still reads as protected.
    const r = maskText('# API_KEY=sk-live-commented-out\nLIVE=1\n')!;
    expect(r.masked).toContain('# API_KEY=«masked:API_KEY»');
    expect(r.masked).not.toContain('sk-live-commented-out');
    expect(r.pairs.some(([, v]) => v === 'sk-live-commented-out')).toBe(true);
  });

  it('leaves ordinary prose in a comment alone', () => {
    const prose = '# This file is automatically generated by Android Studio.';
    const r = maskText(`${prose}\nA=1\n`)!;
    expect(r.masked.split('\n')[0]).toBe(prose);
  });
});

describe('placeholders', () => {
  it('detects and lists them', () => {
    const text = `A=${placeholder('A')} B=${placeholder('B')} A again=${placeholder('A')}`;
    expect(hasPlaceholder(text)).toBe(true);
    expect(placeholdersIn(text)).toEqual([placeholder('A'), placeholder('B')]);
  });

  it('reports none for ordinary text', () => {
    expect(hasPlaceholder('nothing here')).toBe(false);
    expect(placeholdersIn('nothing here')).toEqual([]);
  });
});

describe('vault', () => {
  it('unmasks what it was told', () => {
    const v = createVault();
    v.remember([[placeholder('API_KEY'), 'sk-live-abc123456789']]);
    expect(v.unmask(`key=${placeholder('API_KEY')}`)).toBe('key=sk-live-abc123456789');
    expect(v.size()).toBe(1);
  });

  it('scrubs a value out of arbitrary text', () => {
    const v = createVault();
    v.remember([[placeholder('API_KEY'), 'sk-live-abc123456789']]);
    expect(v.scrub('the command printed sk-live-abc123456789 here')).toBe(
      `the command printed ${placeholder('API_KEY')} here`,
    );
  });

  it('scrubs the LONGEST value first, so a shorter one cannot split it', () => {
    const v = createVault();
    v.remember([
      [placeholder('SHORT'), 'abcdefgh'],
      [placeholder('LONG'), 'abcdefgh-and-more'],
    ]);
    // If the short one ran first, the long value would become
    // `«masked:SHORT»-and-more` and its tail would survive in the clear.
    expect(v.scrub('x abcdefgh-and-more y')).toBe(`x ${placeholder('LONG')} y`);
  });

  it('leaves a value shorter than the scrub floor alone', () => {
    const v = createVault();
    const tiny = 'x'.repeat(MIN_SCRUB_LENGTH - 1);
    v.remember([[placeholder('PW'), tiny]]);
    // It still un-masks — only the sweep is floored.
    expect(v.unmask(placeholder('PW'))).toBe(tiny);
    expect(v.scrub(`pw is ${tiny}`)).toBe(`pw is ${tiny}`);
  });

  it('names the placeholders it does not know', () => {
    const v = createVault();
    v.remember([[placeholder('KNOWN'), 'aaaaaaaaaa']]);
    expect(v.unknownPlaceholders(`${placeholder('KNOWN')} ${placeholder('OTHER')}`)).toEqual([
      placeholder('OTHER'),
    ]);
  });

  it('ignores an empty value', () => {
    const v = createVault();
    v.remember([[placeholder('EMPTY'), '']]);
    expect(v.size()).toBe(0);
  });
});

describe('the copy', () => {
  it('tells the model the one rule that makes the round trip work', () => {
    expect(maskedFileNotice(3)).toContain('write its placeholder back exactly');
    expect(maskedFileNotice(3)).toContain('3 values');
    expect(maskedFileNotice(1)).toContain('1 value');
    expect(maskedFileNotice(1)).not.toContain('1 values');
  });

  it('explains why an unmaskable file was not shown, and how to allow it', () => {
    const t = unmaskableRefusal('release.jks', 'KEY=value');
    expect(t).toContain('release.jks');
    expect(t).toContain('cannot mask it');
    expect(t).not.toContain('protected file.');
    // D49ba: a refusal that does not say how to permit it is a dead end.
    expect(t).toContain('plato.secrets.allow');
  });

  it('names the placeholder it has no value for', () => {
    const t = unknownPlaceholderRefusal(placeholder('API_KEY'));
    expect(t).toContain('«masked:API_KEY»');
    expect(t).toContain('did not write the file');
  });

  it('says value singular for one, values plural for many', () => {
    expect(unknownPlaceholderRefusal(placeholder('A'))).toContain('no real value for it');
    expect(unknownPlaceholderRefusal(`${placeholder('A')}, ${placeholder('B')}`)).toContain(
      'no real values for them',
    );
  });
});

describe('the owner sets the list', () => {
  beforeEach(() => configureSecrets({}));

  it('adds a name the user nominated', () => {
    expect(isSecretPath('config/credentials.json')).toBe(false);
    configureSecrets({ extra: ['credentials.json'] });
    expect(isSecretPath('config/credentials.json')).toBe(true);
  });

  it('adds a wildcard name', () => {
    configureSecrets({ extra: ['*.pem'] });
    expect(isSecretPath('certs/server.pem')).toBe(true);
    expect(isSecretPath('certs/server.crt')).toBe(false);
  });

  it('takes a built-in name OFF the list, by exact path', () => {
    expect(isSecretPath('local.properties')).toBe(true);
    configureSecrets({ allow: ['local.properties'] });
    expect(isSecretPath('local.properties')).toBe(false);
  });

  it('takes off only the path named, not every file with that name', () => {
    configureSecrets({ allow: ['local.properties'] });
    // A different directory's copy is still protected.
    expect(isSecretPath('app/local.properties')).toBe(true);
  });

  it('cannot empty the built-in list with an empty setting', () => {
    configureSecrets({ extra: [], allow: [] });
    expect(isSecretPath('.env')).toBe(true);
    expect(isSecretPath('release.jks')).toBe(true);
  });

  it('ignores blank entries', () => {
    configureSecrets({ extra: ['  '], allow: ['   '] });
    expect(isSecretPath('anything.txt')).toBe(false);
    expect(isSecretPath('.env')).toBe(true);
  });
});
